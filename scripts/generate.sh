#!/bin/bash
#
# Generate TypeScript from XDR definitions for all packages.
# Usage: XDRC=/path/to/x23c ./scripts/generate.sh
#
# The index.ts barrels are hand-written (like lib.rs in protocol-rs).
# This script only regenerates the .ts files from .x files, stamps each one
# with the x23c and protocol commits it was generated from, and records the
# protocol commit in each generated package's package.json.
# scripts/check-codegen-provenance.sh verifies the stamps.

set -euo pipefail

if [[ -z ${XDRC:-} ]]; then
  echo "error: set XDRC to the x23c binary, e.g. XDRC=/path/to/x23c $0" >&2
  exit 1
fi

echo "-- Using XDRC=${XDRC} --" >&2

PROTOCOL_COMMIT=$(git -C protocol rev-parse HEAD)

echo "-- Generating from groundhogchain/protocol@${PROTOCOL_COMMIT} --" >&2

# x23c emits a "DO NOT CHECK IN" banner plus its own commit. These files are
# committed, so replace that with a line naming both inputs.
restamp() {
  local out=$1 source=$2 tmp
  tmp=$(mktemp)
  awk -v source="$source" '
    NR == 2 && /^\/\/ Generated Code: DO NOT CHECK IN$/ { dropped = 1; next }
    NR == 3 && dropped && /^$/ { next }
    NR == 4 && sub(/^\/\/ Generated from x23c commit: /, "") {
      print "// Generated by x23c " $0 " from " source "; do not edit by hand"
      next
    }
    { print }
  ' "$out" > "$tmp"
  if ! grep -q '^// Generated by x23c [0-9a-f]* from ' "$tmp"; then
    echo "error: unexpected x23c banner in $out" >&2
    rm -f "$tmp"
    exit 1
  fi
  cat "$tmp" > "$out"
  rm -f "$tmp"
}

gen_proto() {
  local out=$1 proto=$2
  $XDRC --ts -o "$out" "protocol/${proto}"
  restamp "$out" "groundhogchain/protocol@${PROTOCOL_COMMIT}:${proto}"
}

gen_fixture() {
  local out=$1 src=$2
  $XDRC --ts -o "$out" "$src"
  restamp "$out" "$src"
}

core_protos=(
  types.x db_conflict.x contract.x exec_result.x event.x genesis.x transaction.x
  retrocausal_queue.x storage_cost.x network_config.x syscall_error.x auth_claim.x
  standard_asset_events.x address_auth.x storage_item.x precompiles.x header.x
  validator.x invoke_flag.x network.x
)

rpc_protos=(
  dogwood_kit.x auth_card.x sched_db.x
  wallet.x dogwood_rpc.x event_rpc.x auth_rpc.x test_rpc.x
  discovery.x config.x dogwood.x
  scp.x scp_config.x scp_control.x scp_handle.x
  rpc_types.x parallel.x proposal.x db_sched.x exec_sched.x
  consensus.x sched_coord.x coord_sched.x catchup.x repair.x loadgen.x
)

for proto in "${core_protos[@]}"; do
  gen_proto "packages/protocol/src/protocol/${proto%.x}.ts" "$proto"
done

contract_spec_protos=(
  groundhog_contract_spec.x
)

for proto in "${contract_spec_protos[@]}"; do
  gen_proto "packages/contract-spec/src/protocol/${proto%.x}.ts" "$proto"
done

for proto in "${rpc_protos[@]}"; do
  gen_proto "packages/rpc/src/protocol/${proto%.x}.ts" "$proto"
done

gateway_protos=(
  pagination.x indexer.x
)

for proto in "${gateway_protos[@]}"; do
  gen_proto "packages/gateway/src/protocol/${proto%.x}.ts" "$proto"
done

# Test fixture: echo RPC (standalone, needs proto import line removed)
gen_fixture "packages/rpc/test/fixtures/echo.ts" "packages/rpc/test/fixtures/echo.x"
if [[ "$OSTYPE" == darwin* ]]; then
  sed -i '' '/^import \* as proto/d' "packages/rpc/test/fixtures/echo.ts"
else
  sed -i '/^import \* as proto/d' "packages/rpc/test/fixtures/echo.ts"
fi

# Test fixtures: kitchen-sink XDR types (split into base + compound so
# cross-type refs resolve through the hand-written index.ts barrel)
gen_fixture "packages/protocol/test/fixtures/test_base.ts" "packages/protocol/test/fixtures/test_base.x"
gen_fixture "packages/protocol/test/fixtures/test_compound.ts" "packages/protocol/test/fixtures/test_compound.x"

# Record the protocol commit in each package that ships generated code, so
# the published manifest says which protocol revision it encodes.
for pkg in protocol contract-spec rpc gateway; do
  PROTOCOL_COMMIT=$PROTOCOL_COMMIT node -e '
    const fs = require("fs");
    const path = process.argv[1];
    const manifest = JSON.parse(fs.readFileSync(path, "utf8"));
    manifest.groundhog = { protocolCommit: process.env.PROTOCOL_COMMIT };
    fs.writeFileSync(path, JSON.stringify(manifest, null, 2) + "\n");
  ' "packages/${pkg}/package.json"
done

echo "-- Done --" >&2
